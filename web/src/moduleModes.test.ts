import { describe, expect, it } from 'vitest'
import {
  defaultCurve,
  defaultLiquidity,
  defaultProfitUnwind,
} from './modulePresentation'
import {
  expandModes,
  moduleKeys,
  moduleMode,
  normalizeModes,
  quoteModesDiffer,
  runtimeOn,
  sameConfig,
  withModuleMode,
} from './moduleModes'
import type { Mode, ModulesConfig } from './modules'
import cases from './moduleModeParity.json'

const config = (): ModulesConfig => ({
  mode: 'shadow',
  inventory: {
    enabled: true,
    target_bps: 3000,
    max_bps: 6000,
    max_skew_bps: 50,
    spread_floor_bps: 5,
  },
  spreads: {
    enabled: true,
    inventory_aware: false,
    window_secs: 300,
    warmup_secs: 30,
    multiplier: 1,
    max_extra_bps: 100,
  },
  rebalance: {
    enabled: false,
    method: 'manual',
    trigger_bps: 5000,
    max_trade_bps: 200,
    max_slippage_bps: 50,
    cooldown_secs: 300,
    order_lifetime_secs: 60,
    dealer: null,
  },
  liquidity: defaultLiquidity(),
  curve: defaultCurve(),
  profit_unwind: defaultProfitUnwind(),
})

// Generated by tests/module_mode_parity.rs from the bot's own `mode_of` and
// `normalized`: only the switches, tables in `Module::ALL` order.
type Switches = {
  mode: Mode
  enabled: boolean[]
  own: (Mode | null)[]
  live: boolean
}
type Case = {
  config: Switches
  modes: Mode[]
  normalized: Switches
  quote_modes_differ: boolean
}
const withSwitches = (s: Switches): ModulesConfig => {
  const c = config()
  const next: ModulesConfig = { ...c, mode: s.mode }
  moduleKeys.forEach((key, i) => {
    const { mode: _, ...table } = c[key]
    const own = s.own[i]
    ;(next as unknown as Record<string, unknown>)[key] = {
      ...table,
      enabled: s.enabled[i],
      ...(own ? { mode: own } : {}),
    }
  })
  next.profit_unwind = { ...next.profit_unwind, live: s.live }
  return next
}
const switches = (c: ModulesConfig): Switches => ({
  mode: c.mode,
  enabled: moduleKeys.map((key) => c[key].enabled),
  own: moduleKeys.map((key) => c[key].mode ?? null),
  live: c.profit_unwind.live,
})

describe('module modes match the bot', () => {
  it.each((cases as Case[]).map((c, i) => [i, c] as const))(
    'case %i',
    (_, c) => {
      const input = withSwitches(c.config)
      expect(moduleKeys.map((key) => moduleMode(input, key))).toEqual(c.modes)
      expect(switches(normalizeModes(input))).toEqual(c.normalized)
      expect(quoteModesDiffer(input)).toBe(c.quote_modes_differ)
    }
  )
})

describe('the editor form', () => {
  it('names every running mode, so one edit never moves another module', () => {
    const saved = normalizeModes({ ...config(), mode: 'live' })
    const draft = expandModes(saved)
    expect(draft.inventory.mode).toBe('live')
    expect(draft.rebalance.mode).toBeUndefined()
    // Setting spreads to Preview leaves inventory Live, whatever happens to
    // the shared mode once it is saved.
    const edited = withModuleMode(draft, 'spreads', 'shadow')
    const written = normalizeModes(edited)
    expect(written.mode).toBe('shadow')
    expect(moduleMode(written, 'inventory')).toBe('live')
    expect(moduleMode(written, 'spreads')).toBe('shadow')
    expect(normalizeModes(expandModes(written))).toEqual(written)
  })

  it('keeps profit unwind’s older switch in step with its mode', () => {
    const live = withModuleMode(config(), 'profit_unwind', 'live')
    expect(live.profit_unwind).toMatchObject({ enabled: true, live: true })
    const preview = withModuleMode(live, 'profit_unwind', 'shadow')
    expect(preview.profit_unwind).toMatchObject({ enabled: true, live: false })
    const off = withModuleMode(live, 'profit_unwind', 'off')
    expect(off.profit_unwind.enabled).toBe(false)
    expect(off.profit_unwind.mode).toBeUndefined()
  })

  it('writes the shape older bots read when every module shares a mode', () => {
    const c = withModuleMode(
      withModuleMode(config(), 'inventory', 'live'),
      'spreads',
      'live'
    )
    const written = normalizeModes(c)
    expect(written.mode).toBe('live')
    for (const key of moduleKeys) expect(written[key].mode).toBeUndefined()
    // Keys in the bot's order, so the two serialize alike.
    expect(
      Object.keys(withModuleMode(config(), 'curve', 'live').curve)
    ).toEqual(['enabled', 'mode', 'start_below_mid', 'end_above_buy', 'shape'])
  })

  it('turns the runtime off only when nothing runs and nothing is shared', () => {
    const off = moduleKeys.reduce(
      (c, key) => withModuleMode(c, key, 'off'),
      config()
    )
    expect(runtimeOn(off)).toBe(true)
    expect(runtimeOn(normalizeModes(off))).toBe(false)
    expect(runtimeOn({ ...config(), mode: 'off' })).toBe(false)
    expect(
      runtimeOn(withModuleMode({ ...config(), mode: 'off' }, 'curve', 'live'))
    ).toBe(true)
  })

  it('keeps a Live bot previewing profit unwind in the older shape', () => {
    const c = withModuleMode(
      withModuleMode(config(), 'curve', 'live'),
      'profit_unwind',
      'shadow'
    )
    const written = normalizeModes(
      withModuleMode(withModuleMode(c, 'inventory', 'off'), 'spreads', 'live')
    )
    expect(written.mode).toBe('live')
    expect(written.profit_unwind).toMatchObject({ enabled: true, live: false })
    for (const key of moduleKeys) expect(written[key].mode).toBeUndefined()
    expect(moduleMode(written, 'profit_unwind')).toBe('shadow')
  })

  it('reads a table an older running config leaves out as off', () => {
    const { liquidity: _, ...older } = config()
    expect(moduleMode(older as ModulesConfig, 'liquidity')).toBe('off')
  })

  it('compares configs whatever the key order', () => {
    const a = config()
    const b = { ...a, inventory: { ...a.inventory } }
    const { enabled, ...rest } = b.inventory
    b.inventory = { ...rest, enabled }
    expect(JSON.stringify(a)).not.toBe(JSON.stringify(b))
    expect(sameConfig(a, b)).toBe(true)
    expect(sameConfig(a, withModuleMode(a, 'inventory', 'live'))).toBe(false)
  })
})
