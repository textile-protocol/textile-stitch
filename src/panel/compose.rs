    #[test]
    fn one_bad_field_does_not_turn_a_turnkey_bot_into_a_hot_wallet() {
        // The whole point of this file is recovery, so a service block that looks
        // fine and then can't start on the fresh host is the worst outcome. The
        // signer table stands alone and is read alone, so an unrelated invalid field
        // can't downgrade it.
        let (cfg, root) = test_cfg("brokensigner");
        let corridor = crate::setup::find_corridor("cngn-usdt-bsc").unwrap();
        let toml = format!(
            "{}\n[signer]\nprovider = \"turnkey\"\norganization_id = \"org-1\"\n\
             sign_with = \"0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266\"\n\
             operator_address = \"0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266\"\n",
            corridor
                .toml_template
                .replace("tick_interval_secs = 5", "tick_interval_secs = \"soon\"")
        );
        std::fs::create_dir_all(root.join("bot-a")).unwrap();
        std::fs::write(root.join("bot-a").join("stitch.toml"), &toml).unwrap();
        // The loader really does reject this config, which is what used to make the
        // signer read as local.
        assert!(crate::config::Config::from_toml(&toml).is_err());

        let mut c = container("stitch-bot-a", ContainerState::Running);
        c.labels.insert(LABEL_BOT.into(), "bot-a".into());
        c.mounts = dir_layout_mounts("/host/stitch/bot-a");

        let yaml = render(&discover(&[c], &cfg), &cfg);
        assert!(
            yaml.contains("TURNKEY_API_PRIVATE_KEY_FILE"),
            "the real signer has to survive one bad field: {yaml}"
        );
        assert!(
            !yaml.contains("STITCH_PRIVATE_KEY_FILE"),
            "it must not be exported as a hot wallet: {yaml}"
        );
        std::fs::remove_dir_all(&root).ok();
    }

