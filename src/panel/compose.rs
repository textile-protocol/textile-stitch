    #[test]
    fn a_stopped_bot_is_not_brought_back_up_by_the_recovery_command() {
        // The header tells the operator to run `docker compose up -d`, and that
        // starts every service in the file. A bot someone stopped deliberately
        // must not come back on the book because the fleet was restored.
        let (cfg, root) = test_cfg("stopped");
        seed(&root, "live");
        seed(&root, "paused");

        let mut live = container("stitch-live", ContainerState::Running);
        live.labels.insert(LABEL_BOT.into(), "live".into());
        live.mounts = dir_layout_mounts("/host/stitch/live");

        let mut paused = container("stitch-paused", ContainerState::Exited);
        paused.labels.insert(LABEL_BOT.into(), "paused".into());
        paused.mounts = dir_layout_mounts("/host/stitch/paused");

        let yaml = render(&discover(&[live, paused], &cfg), &cfg);
        let key = "\n    profiles: [stopped]\n";
        assert_eq!(
            yaml.matches(key).count(),
            1,
            "only the stopped bot is held back: {yaml}"
        );
        // And it's under that bot, not the running one.
        let paused_at = yaml.find("\n  paused:").unwrap();
        let live_at = yaml.find("\n  live:").unwrap();
        assert!(yaml.find(key).unwrap() > paused_at.max(live_at), "{yaml}");
        // The service itself is still fully described, so it can be started.
        assert!(yaml.contains("- ./paused:/home/stitch/run"), "{yaml}");
        assert!(
            yaml.contains("docker compose --profile stopped up -d paused"),
            "{yaml}"
        );
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn a_bot_pinned_to_another_image_keeps_it() {
        // The anchor carries the panel's image. Recovering from this file has to
        // bring each bot back on the binary it was running, not silently upgrade
        // the ones an operator pinned somewhere else.
        let (cfg, root) = test_cfg("pinned");
        seed(&root, "bot-a");
        seed(&root, "bot-b");

        let mut same = container("stitch-bot-a", ContainerState::Running);
        same.labels.insert(LABEL_BOT.into(), "bot-a".into());
        same.mounts = dir_layout_mounts("/host/stitch/bot-a");
        same.image = cfg.bot_image.clone();

        let mut pinned = container("stitch-bot-b", ContainerState::Running);
        pinned.labels.insert(LABEL_BOT.into(), "bot-b".into());
        pinned.mounts = dir_layout_mounts("/host/stitch/bot-b");
        pinned.image = "ghcr.io/acme/stitch-fork:v9".into();

        let yaml = render(&discover(&[same, pinned], &cfg), &cfg);
        assert!(
            yaml.contains("image: ghcr.io/acme/stitch-fork:v9"),
            "{yaml}"
        );
        // The one already on the panel's image inherits it from the anchor rather
        // than repeating it.
        assert_eq!(
            yaml.matches("image: ").count(),
            2,
            "only the anchor and the pinned bot should name an image: {yaml}"
        );
        std::fs::remove_dir_all(&root).ok();
    }

