    #[test]
    fn a_flat_layout_bot_exports_the_paths_it_actually_has() {
        // Normalising this bot to ./bot1/stitch.toml would name a path that
        // doesn't exist, and `docker compose up` turns a missing bind source into
        // an empty root-owned directory — so the config mount would land as a
        // directory and the bot would never start. The recovery file has to
        // reproduce what runs today.
        let (cfg, root) = test_cfg("flat");
        let corridor = setup::find_corridor("cngn-usdt-bsc").unwrap();
        std::fs::write(root.join("stitch.bot1.toml"), corridor.toml_template).unwrap();
        std::fs::write(
            root.join("stitch.bot1.key"),
            "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80\n",
        )
        .unwrap();

        let mut c = container("stitch-bot1", ContainerState::Running);
        c.labels.insert(LABEL_COMPOSE_SERVICE.into(), "bot1".into());
        c.mounts = flat_layout_mounts("/host/stitch", "bot1");

        let fleet = discover(&[c], &cfg);
        assert_eq!(fleet.get("bot1").unwrap().layout, Layout::FlatFiles);
        let yaml = render(&fleet, &cfg);

        assert!(yaml.contains("  bot1:\n"), "{yaml}");
        assert!(
            yaml.contains("./stitch.bot1.toml:/home/stitch/run/stitch.toml:ro"),
            "{yaml}"
        );
        assert!(
            yaml.contains("./stitch.bot1.key:/home/stitch/run/stitch.key:ro"),
            "{yaml}"
        );
        // Nothing may point at the per-bot directory it doesn't have.
        assert!(!yaml.contains("./bot1/"), "{yaml}");
        // No writable mount, so the ledger note must not be claimed here.
        assert!(!yaml.contains("persists the nonce ledger"), "{yaml}");
        // And the export says what that costs and how to fix it.
        assert!(yaml.contains("migrate it in the panel"), "{yaml}");
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn exports_panel_native_and_adopted_bots_together() {
        let (cfg, root) = test_cfg("both");
        seed(&root, "bot-a");
        seed(&root, "bot-b");

        let mut native = container("stitch-bot-a", ContainerState::Running);
        native.labels.insert(LABEL_BOT.into(), "bot-a".into());
        native.mounts = dir_layout_mounts("/host/stitch/bot-a");

        let mut adopted = container("stitch-bot-b", ContainerState::Running);
        adopted
            .labels
            .insert(LABEL_COMPOSE_SERVICE.into(), "bot-b".into());
        adopted
            .labels
            .insert(LABEL_COMPOSE_PROJECT.into(), "stitch".into());
        adopted.mounts = dir_layout_mounts("/host/stitch/bot-b");

        let fleet = discover(&[native, adopted], &cfg);
        let yaml = render(&fleet, &cfg);

        assert!(yaml.contains("  bot-a:\n"));
        assert!(yaml.contains("  bot-b:\n"));
        assert!(yaml.contains("container_name: stitch-bot-a"));
        assert!(yaml.contains("x-stitch: &stitch"));
        // The bot only checks for shutdown between ticks, so a recovery file that
        // leaves compose on its 10s default would kill it mid-tick on every
        // `docker compose stop`.
        assert!(yaml.contains("stop_grace_period: 30s"), "{yaml}");
        assert!(yaml.contains("<<: *stitch"));
        // The adopted one says where it came from.
        assert!(yaml.contains("Adopted from compose project \"stitch\""));
        std::fs::remove_dir_all(&root).ok();
    }

