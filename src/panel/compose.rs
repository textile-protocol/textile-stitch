    #[test]
    fn scalars_that_yaml_would_reinterpret_get_quoted() {
        // An image tag like "1.0" would otherwise load as a float, and "no" as a
        // boolean.
        assert_eq!(yaml_scalar("1.0"), "'1.0'");
        assert_eq!(yaml_scalar("no"), "'no'");
        assert_eq!(yaml_scalar("true"), "'true'");
        assert_eq!(yaml_scalar(""), "''");
        assert_eq!(yaml_scalar(" leading"), "' leading'");
        assert_eq!(yaml_scalar("*anchor"), "'*anchor'");
        assert_eq!(yaml_scalar("a: b"), "'a: b'");
        // Ordinary values are left bare, which keeps the file readable.
        assert_eq!(yaml_scalar("info"), "info");
        assert_eq!(
            yaml_scalar("ghcr.io/textile-protocol/textile-stitch:latest"),
            "ghcr.io/textile-protocol/textile-stitch:latest"
        );
        // An embedded quote is doubled, YAML's own escape.
        assert_eq!(yaml_scalar("it's"), "'it''s'");
    }

