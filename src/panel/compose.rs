//! Generate a `docker-compose.yml` for the whole fleet.
//!
//! Strictly one-way. The panel never reads a compose file back, and never edits
//! one in place: doing that would mean parsing YAML the operator hand-wrote,
//! losing their anchors and comments, and handing back something they no longer
//! recognise. Instead the export is a fresh, canonical file, and its header says
//! so.
//!
//! The reason it exists is recovery. Everything the panel manages lives in
//! containers and config directories, both of which outlive the panel — but
//! rebuilding a fleet from `docker run` invocations by hand is miserable. With
//! this file an operator can bring the whole fleet back with `docker compose up
//! -d` on a fresh host, panel or no panel.
//!
//! It is canonical rather than a byte-for-byte capture: services are rendered
//! from each bot's config the way the panel would create it, so an adopted bot
//! with an unusual hand-written service comes out normalised. Mounts are the
//! exception — they're rendered from the layout the bot actually has, because a
//! bot on the flat layout normalised to per-bot directory paths would name
//! directories that don't exist and fail to start. Anything the panel could not
//! represent faithfully is called out in a comment instead of being quietly
//! dropped.

use std::path::{Path, PathBuf};

use crate::panel::config::PanelConfig;
use crate::panel::docker::STOP_GRACE_SECS;
use crate::panel::inventory::{Bot, Fleet, Layout, Origin};
use crate::panel::naming::{container_name, validate_bot_id};
use crate::panel::provision::{image_of, mounts_for, signer_runtime_at};

/// Compose profile holding back the bots that weren't running at export time.
/// Named for what it means, because the operator sees it on the command line.
const STOPPED_PROFILE: &str = "stopped";

/// Render the fleet as a compose file.
pub fn render(fleet: &Fleet, cfg: &PanelConfig) -> String {
    let mut out = String::new();
    out.push_str(&header(fleet));
    out.push_str(&anchor(cfg));
    out.push_str("\nservices:\n");

    let mut rendered = 0usize;
    for bot in fleet.bots() {
        match service(bot, cfg) {
            Ok(block) => {
                out.push_str(&block);
                rendered += 1;
            }
            Err(reason) => {
                out.push_str(&format!(
                    "  # {} was not exported: {reason}\n",
                    yaml_comment(&bot.name)
                ));
            }
        }
    }
    if rendered == 0 {
        out.push_str("  {} # no bots to export yet\n");
    }
    out
}

fn header(fleet: &Fleet) -> String {
    format!(
        "# Generated by the Stitch admin panel. {} bot(s).\n\
         #\n\
         # This file is written fresh every time you export it. The panel never reads it\n\
         # back and never edits it in place, so anything you add here is yours to keep\n\
         # track of — the next export will not preserve it.\n\
         #\n\
         # What it's for: recovery. Copy it next to your bot directories and run\n\
         # `docker compose up -d` to rebuild the whole fleet on a fresh host, with or\n\
         # without the panel.\n\
         #\n\
         # Bring the fleet up:      docker compose up -d\n\
         # Add or change one bot:   docker compose up -d <bot-name>\n\
         #\n\
         # Bots that were not up when this was exported carry\n\
         # `profiles: [{STOPPED_PROFILE}]`, so the command above leaves them stopped — a bot\n\
         # someone stopped deliberately should not come back on the book by itself. A bot\n\
         # Docker was restarting counts as up: it was meant to be running, and this file\n\
         # is often how you recover onto a host where it finally will.\n\
         # Start a held-back one with `docker compose --profile {STOPPED_PROFILE} up -d <bot-name>`.\n\
         #\n\
         # A bot with its own directory has it mounted read-write at /home/stitch/run,\n\
         # which is what keeps its slot-nonce ledger on the host across container\n\
         # recreation. The config and the signer secret are re-mounted read-only on top.\n\
         # Those directories must be owned by uid 1000 so the container user can write.\n\
         #\n\
         # A bot still on the flat file layout is exported as it runs today: its config\n\
         # and key mounted individually, no writable directory, so its ledger stays\n\
         # inside the container and is lost on recreation. Migrate it in the panel to\n\
         # move it onto the host.\n",
        fleet.len()
    )
}

/// The shared settings block. Bots reference it with a YAML merge key, which is
/// what the hand-written production file does, so an operator reading the export
/// sees a familiar shape.
fn anchor(cfg: &PanelConfig) -> String {
    format!(
        "\nx-stitch: &stitch\n\
         \x20 image: {}\n\
         \x20 restart: unless-stopped\n\
         \x20 # The bot only checks for shutdown between ticks, so compose's default\n\
         \x20 # 10s would kill it mid-tick.\n\
         \x20 stop_grace_period: {STOP_GRACE_SECS}s\n\
         \x20 logging:\n\
         \x20   driver: json-file\n\
         \x20   options:\n\
         \x20     max-size: \"10m\"\n\
         \x20     max-file: \"5\"\n",
        yaml_scalar(&cfg.bot_image)
    )
}

/// Where this bot's files sit, as the compose file will name them, plus a comment
/// when that path needs explaining.
///
/// The operator is told to put the file beside their bot directories, so a relative
/// path is what makes the export portable. But the directory name is *not* the bot
/// name: an adopted compose service called `foo` can mount `<bots root>/custom`, and
/// inventory names the bot after the service. Synthesising `./foo` from the name
/// produced a recovery file whose config and secret paths simply don't exist —
/// nothing is renamed or copied at export time.
///
/// So the path comes from the mount the bot actually has. A config outside the bots
/// root can't be expressed relative to the file at all, and there the absolute host
/// path is the only faithful answer: it works on this host, which is the one being
/// recovered most of the time. It gets a comment, because it's also the one line in
/// the file that won't survive being copied somewhere else.
fn mount_base(bot: &Bot, cfg: &PanelConfig) -> (PathBuf, Option<String>) {
    // A flat-layout bot's files sit loose in the root next to everyone else's, so
    // the compose file's own directory is the base.
    if bot.layout == Layout::FlatFiles {
        return (PathBuf::from("."), None);
    }
    let Some(dir) = bot.config_host_path.as_ref().and_then(|p| p.parent()) else {
        // No mount to read: fall back to the panel's own naming, which is right for
        // every bot the panel created.
        return (Path::new(".").join(&bot.name), None);
    };
    match dir.strip_prefix(&cfg.host_bots_dir) {
        Ok(rest) => (Path::new(".").join(rest), None),
        Err(_) => (
            dir.to_path_buf(),
            Some(format!(
                "    # Its config lives at {} on the host, outside {}, so this mount is an\n\
                 \x20   # absolute path. It will not follow this file to another machine — copy\n\
                 \x20   # the directory and edit the path if you're recovering elsewhere.\n",
                yaml_comment(&dir.display().to_string()),
                yaml_comment(&cfg.host_bots_dir.display().to_string()),
            )),
        ),
    }
}

/// One service block, or the reason this bot can't be represented.
fn service(bot: &Bot, cfg: &PanelConfig) -> Result<String, String> {
    // A compose service key and a container name have to be safe, and an adopted
    // bot's name came from someone else's compose file rather than our validator.
    validate_bot_id(&bot.name)
        .map_err(|e| format!("its name isn't usable as a compose service ({e})"))?;

    let config = bot
        .config_panel_path
        .as_ref()
        .ok_or_else(|| "the panel can't read its config file".to_string())?;
    // A guess here would be worse than an omission. Exporting a Turnkey bot with the
    // hot wallet's mounts and env produces a service block that looks fine, restores
    // fine, and then can't start — and the operator only finds out on the fresh host
    // they're recovering onto. `render` turns this into a `# <bot> was not exported:`
    // line, which is a problem they can see and fix.
    let signer = signer_runtime_at(config).map_err(|e| {
        format!(
            "the panel can't tell which signer it uses, so exporting it would bake in the \
                 wrong secret and environment ({e:#})"
        )
    })?;
    let (base, base_note) = mount_base(bot, cfg);
    let mounts = mounts_for(bot, &base, &signer)?;

    let mut block = format!(
        "  {}:\n    <<: *stitch\n    container_name: {}\n",
        bot.name,
        yaml_scalar(&container_name(&bot.name))
    );

    // The anchor carries the panel's image; a bot running something else keeps it,
    // so recovering from this file doesn't swap its trading binary.
    let image = image_of(bot, cfg);
    if image != cfg.bot_image {
        block.push_str(&format!("    image: {}\n", yaml_scalar(&image)));
    }

    if let Origin::Compose { project, .. } = &bot.origin {
        let which = project.as_deref().unwrap_or("unknown");
        block.push_str(&format!(
            "    # Adopted from compose project \"{}\".\n",
            yaml_comment(which)
        ));
    }
    // A bot that wasn't up was down for a reason, and `docker compose up -d` starts
    // every service it can see. A compose profile keeps the service definition intact
    // while leaving it out of the default set, so recovering the fleet restores the
    // fleet's state rather than putting a bot someone stopped back on the book.
    //
    // `wants_to_be_up` rather than `is_running`, so a crash-looping bot is exported
    // as part of the default set: `restarting` isn't quoting this instant, but it's a
    // bot the operator means to have up, and holding it back would quietly not bring
    // it back on the host they're recovering onto.
    if !bot.state.wants_to_be_up() {
        block.push_str(&format!(
            "    # Not running when this was exported ({}), so it is held back from\n\
             \x20   # `docker compose up -d`. Start it with:\n\
             \x20   #   docker compose --profile {STOPPED_PROFILE} up -d {}\n\
             \x20   profiles: [{STOPPED_PROFILE}]\n",
            yaml_comment(bot.state.as_str()),
            yaml_comment(&bot.name)
        ));
    }

    if let Some(note) = &base_note {
        block.push_str(note);
    }

    if bot.layout == Layout::FlatFiles {
        block.push_str(
            "    # Kept on the flat file layout, so this comes back exactly as it runs today.\n\
             \x20   # Its nonce ledger lives inside the container and is lost on recreation:\n\
             \x20   # migrate it in the panel to move it onto the host.\n",
        );
    }

    block.push_str("    environment:\n      RUST_LOG: info\n");
    for var in &signer.env {
        // Signer env is generated as KEY=value; compose wants a mapping.
        if let Some((key, value)) = var.split_once('=') {
            block.push_str(&format!("      {key}: {}\n", yaml_scalar(value)));
        }
    }

    block.push_str("    volumes:\n");
    for m in &mounts {
        let spec = m
            .to_bind_string()
            .map_err(|e| format!("one of its mounts can't be expressed in compose ({e})"))?;
        // Only the writable directory mount earns the note, and a flat-layout bot
        // doesn't have one — which is exactly why its ledger doesn't survive.
        let note = if m.read_only {
            ""
        } else {
            " # rw: persists the nonce ledger across restarts"
        };
        block.push_str(&format!("      - {}{note}\n", yaml_scalar(&spec)));
    }
    block.push('\n');
    Ok(block)
}

/// Quote a YAML scalar when it would otherwise be ambiguous.
///
/// Compose values here are image refs, paths and env values. The risky ones are
/// values that YAML would read as a number, a bool, or null, and values with
/// leading/trailing space or a character that starts a YAML construct.
fn yaml_scalar(value: &str) -> String {
    let needs_quotes = value.is_empty()
        || value != value.trim()
        || value.parse::<f64>().is_ok()
        || matches!(
            value.to_lowercase().as_str(),
            "true" | "false" | "yes" | "no" | "on" | "off" | "null" | "~"
        )
        || value.starts_with(['&', '*', '!', '%', '@', '`', '>', '|', '{', '[', '?', '-', '#'])
        || value.contains(": ")
        || value.contains(" #")
        || value.contains('\n')
        // A bare scalar containing a quote is legal YAML, but quoting it anyway
        // keeps one escaping rule instead of two.
        || value.contains('\'')
        || value.contains('"');
    if needs_quotes {
        // Single quotes are YAML's literal form; the only escape needed is a
        // doubled quote.
        format!("'{}'", value.replace('\'', "''"))
    } else {
        value.to_string()
    }
}

/// Make a value safe to interpolate into a `#` comment line: a newline would end
/// the comment and turn the rest into YAML.
fn yaml_comment(value: &str) -> String {
    value.replace(['\n', '\r'], " ")
}

